# ---- formulas (copied from scripts/fe803b80/core.py; see tests) -------------------------
SOURCE_WEIGHTS = {"pinnacle": 2.0, "bovada": 1.5, "kalshi": 1.0, "melbet": 1.0, "thunderpick": 1.5}
VALVE_RD = 75.0
VALVE_Q = math.log(10) / 400.0
VALVE_G = 1.0 / math.sqrt(1.0 + 3.0 * VALVE_Q ** 2 * VALVE_RD ** 2 / math.pi ** 2)
VALVE_C = VALVE_G * math.log(10) / 400.0
COIN_FLIP_BAND = 0.03


def no_vig(dec_a, dec_b):
    da, db = float(dec_a), float(dec_b)
    if da <= 1.0 or db <= 1.0:
        return None
    ia, ib = 1.0 / da, 1.0 / db
    book = ia + ib
    if not 0.95 <= book <= 1.30:
        return None
    return {"prob_a": ia / book, "prob_b": ib / book, "overround": book - 1.0}


def consensus(entries):
    usable = [e for e in entries if isinstance(e.get("prob_a"), float)]
    if not usable:
        return None
    wsum = sum(SOURCE_WEIGHTS.get(e["source_key"], 1.0) for e in usable)
    pa = sum(SOURCE_WEIGHTS.get(e["source_key"], 1.0) * e["prob_a"] for e in usable) / wsum
    return {"prob_a": pa, "n_sources": len(usable), "sources": sorted({e["source_key"] for e in usable})}


def sigmoid(x):
    return 1.0 / (1.0 + math.exp(-x))


def vrs_prob(points_a, points_b, k):
    return sigmoid(k * VALVE_C * (float(points_a) - float(points_b)))


# ---- helpers ----------------------------------------------------------------------------
def malta(iso_utc: str) -> str:
    dt = datetime.strptime(iso_utc, "%Y-%m-%dT%H:%M:%SZ").replace(tzinfo=timezone.utc)
    return dt.astimezone(MALTA).strftime("%a %d %b %H:%M")


def pct(p):
    return f"{p * 100:.1f}%"


def recompute_market(row):
    """Re-derive the board's market probability for team_a from the stored quotes."""
    entries = []
    for q in row.get("quotes", []):
        nv = no_vig(q.get("decimal_a"), q.get("decimal_b"))
        if nv is None:
            continue
        entries.append({"source_key": q["source_key"], "prob_a": nv["prob_a"]})
    return consensus(entries)


