        fid = r["fixture_id"]
        market = r.get("market") or {}
        model = r.get("model") or {}
        recomputed_market = recompute_market(r)
        market_check = None
        if market.get("prob_a") is not None and recomputed_market is not None:
            market_check = abs(recomputed_market["prob_a"] - market["prob_a"]) <= 1e-4  # board rounds market to 5 dp
        vrs = model.get("vrs")
        vrs_check = None
        if vrs and model.get("prob_a") is not None:
            vrs_check = abs(vrs_prob(vrs["points_a"], vrs["points_b"], k) - model["prob_a"]) < 1e-9

        # Basis: market first (board rule), then Valve VRS, then originated Elo, else none.
        pa, basis, n_src, srcs = None, None, 0, []
        if market.get("prob_a") is not None:
            pa, basis, n_src, srcs = market["prob_a"], "market", market.get("n_sources", 0), market.get("sources", [])
        elif model.get("prob_a") is not None:
            pa = model["prob_a"]
            basis = model.get("basis") or "model"
        pick_team = None
        exact_tie = pa is not None and abs(pa - 0.5) < 1e-9
        if pa is not None and not exact_tie:
            pick_team = r["team_a"] if pa > 0.5 else r["team_b"]
        flags = []
        if basis == "market" and n_src == 1:
            flags.append("single-book line")
        if basis == "market" and srcs == ["melbet"] and pa is not None and abs(pa - 0.5) < 1e-9:
            flags.append("dead-even single book (no pick published)")
        if basis != "market" and basis is not None:
            flags.append("model only (no bookmaker line)")
        if pa is not None and abs(pa - 0.5) < COIN_FLIP_BAND:
            flags.append("coin flip (within 3 points of 50%)")
        if pa is None:
            flags.append("UNRESOLVED: no market, no Valve VRS, no Elo basis")
        if exact_tie:
            flags.append("UNRESOLVED: exact 50/50 on a single book, no pick published")

        rows_out.append({
            "fixture_id": fid, "competition": r.get("competition"), "tier": r.get("tier"),
            "start_utc": r["start_utc"], "lock_utc": r.get("lock_utc"),
            "team_a": r["team_a"], "team_b": r["team_b"],
            "hotspawn_url": r.get("hotspawn_url"),
            "quote_urls": sorted({q["public_url"] for q in r.get("quotes", []) if q.get("public_url")}),
            "pick": pick_team, "prob_team_a": pa, "basis": basis,
            "n_sources": n_src, "sources": srcs,
            "checks": {"market_rederived_from_quotes": market_check, "vrs_rederived": vrs_check},
            "flags": flags, "source": "data/fe803b80/board.json (read-only)",
        })

